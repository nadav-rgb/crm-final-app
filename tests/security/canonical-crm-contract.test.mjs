test('I1 tour contract uses text IDs, tour_number mapping and required legacy fields', async () => {
  assert.equal(tourIdCommandSchema.safeParse({ tourId: 'tour-sheet-123' }).success, true);
  assert.equal(tourCommandSchema.safeParse({ title: 'Tour only' }).success, false);
  const ctx = context({ memberships: [{ projectId: 1, role: 'coord', status: 'active' }] });
  const created = await createTourCommand(ctx, { title: 'Tour 12', settlement: 'Synthetic' }, {
    createId: () => 'server-tour-id',
  });
  assert.equal(created.id, 'server-tour-id');
  assert.equal(created.tour_number, 'Tour 12');
  assert.equal(created.settlement, 'Synthetic');
  assert.equal(created.date, undefined);
  assert.equal(created.guide_name, undefined);
  const updated = await updateTourCommand(ctx, {
    id: 'tour-sheet-123', project_id: 1, status: 'upcoming', assigned_user_ids: [],
  }, { title: 'Renamed' });
  assert.deepEqual(updated, { tour_number: 'Renamed' });
});

