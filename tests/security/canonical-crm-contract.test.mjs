test('I1 faithful CRM fixture uses the repository legacy ID and column contract', async () => {
  const sql = await read('tests/security/fixtures/legacy-security-schema.sql');
  const contacts = sql.match(/create table public\.contacts\s*\([\s\S]*?\n\);/i)?.[0] ?? '';
  const interactions = sql.match(/create table public\.interactions\s*\([\s\S]*?\n\);/i)?.[0] ?? '';
  const tours = sql.match(/create table public\.tours\s*\([\s\S]*?\n\);/i)?.[0] ?? '';

  assert.match(contacts, /id\s+bigint\s+generated by default as identity primary key/i);
  for (const column of [
    'is_active', 'area', 'depth', 'profession', 'age', 'gender', 'high_potential',
    'days_since_last_contact', 'last_interaction_date', 'next_action', 'next_action_date',
    'source', 'joined_at', 'how_met', 'mitzvot', 'mitzvot_history', 'is_graduate',
    'referred_by', 'meeting_place_city', 'meeting_place_number', 'tour_id',
    'meetingHouseCity', 'meetingHouseNumber', 'meetingHouseKey',
  ]) assert.match(contacts, new RegExp(`"?${column}"?\\s`, 'i'), `contacts.${column} missing`);
  assert.doesNotMatch(contacts, /\bstatus\b|\bnext_action_at\b/i);

  assert.match(interactions, /id\s+bigint\s+generated by default as identity primary key/i);
  assert.match(interactions, /contact_id\s+bigint/i);
  for (const column of [
    'date', 'time', 'duration_minutes', 'outcome', 'description', 'ai_summary',
    'next_action', 'next_action_date', 'notes', 'participants',
  ]) assert.match(interactions, new RegExp(`\\b${column}\\b`, 'i'), `interactions.${column} missing`);
  assert.doesNotMatch(interactions, /\boccurred_at\b/i);

  assert.match(tours, /id\s+text\s+primary key/i);
  assert.match(tours, /tour_number\s+text\s+not null/i);
  assert.match(tours, /settlement\s+text\s+not null/i);
  assert.doesNotMatch(tours, /\btitle\b/i);
});

test('I1 contact create requires explicit authorized project and preserves operational fields', async () => {
  assert.equal(contactCreateSchema.safeParse(contactInput).success, true);
  const command = await createContactCommand(context(), contactInput, {
    isActiveMember: async (projectId, userId) => projectId === 2 && userId === USER_B,
  });
  assert.equal(command.project_id, 2);
  assert.equal(command.assigned_user_id, USER_A);
  assert.deepEqual(command.mitzvot, { synthetic: 1 });
  assert.deepEqual(command.mitzvot_history, contactInput.mitzvotHistory);
  for (const column of [
    'area', 'depth', 'profession', 'age', 'gender', 'high_potential',
    'days_since_last_contact', 'last_interaction_date', 'next_action', 'next_action_date',
    'source', 'joined_at', 'how_met', 'is_graduate', 'referred_by',
    'meeting_place_city', 'meeting_place_number', 'meetingHouseCity',
    'meetingHouseNumber', 'meetingHouseKey', 'tour_id',
  ]) assert.equal(column in command, true, `${column} was dropped`);

  await assert.rejects(
    () => createContactCommand(context(), { ...contactInput, projectId: undefined }),
    (error) => error instanceof SecurityError && error.code === 'PROJECT_REQUIRED',
  );
  await assert.rejects(
    () => createContactCommand(context(), { ...contactInput, projectId: 3 }),
    (error) => error instanceof SecurityError && error.code === 'PROJECT_REQUIRED',
  );
});

